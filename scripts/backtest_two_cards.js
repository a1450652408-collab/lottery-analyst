/* ---- 6. 复刻选七卡片引擎 ---- */
function picks7(targetP) {
  const hist = periods.filter(p => p < targetP).sort((a,b)=>b-a).map(p => all[p]);
  if (hist.length < 60) throw new Error("history too short for " + targetP);
  const use = hist.slice(0, 50);          // data.slice(0,50)
  const r10 = hist.slice(0, 10);          // 奇偶预测用 data.slice(0,10)

  // EMA (半衰期2期, 旧→新)
  const ema = {};
  for (let n = 1; n <= 80; n++) {
    const seq = use.map(it => it.n.indexOf(n) >= 0 ? 1 : 0);
    let e = seq[seq.length-1];
    for (let j = seq.length-2; j >= 0; j--) e = 0.5*seq[j] + 0.5*e;
    ema[n] = e;
  }
  // 动量 近5 vs 前5
  const R5 = {}, P5 = {};
  for (let n=1;n<=80;n++){R5[n]=0;P5[n]=0;}
  use.slice(0,10).forEach((it,j)=>it.n.forEach(n=>{ if(j<5)R5[n]++; else P5[n]++; }));
  const mom = {};
  for (let n=1;n<=80;n++){ const mm=(R5[n]-P5[n])/Math.max(P5[n],1); mom[n]=Math.max(-2,Math.min(2,mm)); }
  // 频率 近30
  const f30 = {};
  for (let n=1;n<=80;n++) f30[n]=0;
  use.slice(0,30).forEach(it=>it.n.forEach(n=>f30[n]++));

  // 池内冷热温
  const sc = POOL.map(n => ({n, s:(ema[n]||0)*5 + ((f30[n]||0)/30)*3 + (mom[n]||0)*2}));
  sc.sort((a,b)=>b.s-a.s);
  const hot = sc.slice(0,6).map(x=>x.n), warm = sc.slice(6,16).map(x=>x.n), cold = sc.slice(16).map(x=>x.n);
  // 奇偶预测 (近10期池内号平均奇数个数)
  let os=0, oc=0;
  r10.forEach(it=>{ const ns=it.n.filter(n=>POOL.indexOf(n)>=0); if(ns.length){ os+=ns.filter(n=>n%2===1).length; oc++; } });
  const op = oc ? Math.round(os/oc) : 4;
  // 候选打分 → top50 (稳定排序)
  const scored = CAND.map(t=>{
    const hc=t.filter(n=>hot.indexOf(n)>=0).length;
    const wc=t.filter(n=>warm.indexOf(n)>=0).length;
    const cc=t.filter(n=>cold.indexOf(n)>=0).length;
    const oc2=t.filter(n=>n%2===1).length;
    const s=hc*2+wc*1+cc*(-1)+(Math.abs(oc2-op)<=1?1:0);
    return {t,s};
  });
  scored.sort((a,b)=>b.s-a.s);
  return scored.slice(0,50).map(x=>x.t);
}

